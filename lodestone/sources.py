def render_markdown(rows: list[dict], seed: list[dict]) -> str:
    """A readable view of the index for GitHub: every watched company and where its jobs come from."""
    from collections import Counter
    seg = {r["company"].strip(): r.get("segment", "") for r in seed}
    bc = by_company(rows)
    active = [r for r in rows if r["status"] == "active"]
    lines = [
        "# Lodestone source index",
        "",
        "Where every company on the watchlist publishes its jobs, and how Lodestone reads them.",
        "Generated by `python3 -m lodestone index` from [`source_index.csv`](source_index.csv) (the file the engine uses).",
        "Canada counts are from the last refresh.",
        "",
        f"**{len(seg)} companies** · **{len({r['company'] for r in active})} with a working feed** "
        f"({len(active)} sources) · **{sum(1 for c in seg if c not in {r['company'] for r in active})} without one**",
        "",
        "| Job system | Companies |",
        "|---|---|",
    ]
    for p, n in Counter(r["platform"] for r in active).most_common():
        lines.append(f"| {PLATFORM_LABELS.get(p, p)} | {n} |")
    lines += ["", "## By company", "", "| Company | Segment | Job system | Status | Canada roles | Careers site | Notes |",
              "|---|---|---|---|---|---|---|"]
    status_label = {"active": "✅ Pulled", "paused": "⏸ Paused", "no_feed": "✋ Paste only"}
    for name in sorted(seg, key=str.lower):
        for r in bc.get(name, [{"platform": "", "status": "", "notes": "Not yet researched"}]):
            link = f"[open]({r['careers_url']})" if r.get("careers_url") else ""
            note = (r.get("notes") or "").replace("|", "/").replace("\n", " ")
            note = note[:140] + ("…" if len(note) > 140 else "")
            lines.append(f"| {name} | {seg.get(name, '')} | {PLATFORM_LABELS.get(r['platform'], r['platform'])} | "
                         f"{status_label.get(r['status'], r['status'])} | {r.get('canada_jobs', '')} | {link} | {note} |")
    lines += ["", "**Status:** ✅ Pulled on every refresh · ⏸ Paused (found but unconfirmed or empty) · "
              "✋ Paste only (no machine-readable feed; add roles with paste capture, A3)", ""]
    return "\n".join(lines)


def row_host(r: dict) -> str | None:
    """The web host a source row talks to (for the network check, D-038)."""
    import urllib.parse
    f, p = r.get("feed") or {}, r["platform"]
    if f.get("host"):
        return f["host"]
    for k in ("board_url", "search_url"):
        if f.get(k):
            return urllib.parse.urlparse(f[k]).netloc
    if p == "bamboohr":
        return f"{f['subdomain']}.bamboohr.com"
    if p == "page":
        return urllib.parse.urlparse(f["url"]).netloc
    if p == "hibob":
        return f"{f['subdomain']}.careers.hibob.com"
    from .adapters import ADAPTERS
    a = ADAPTERS.get(p)
    return a.host if a and "." in a.host else None
